// ============================================================================
// layout.tsx —— 全站"总外壳"（Root Layout）
// ============================================================================
// 【先回答一个关键问题：这是不是用 HTML 写的？】
//
// 不是。这个文件是 TypeScript + JSX。后缀 .tsx 就是线索：
//   .ts —— TypeScript（带类型检查的 JavaScript）
//   x   —— JSX（在 JS 里直接写"像 HTML 的标签"的语法扩展）
//
// 它长得像 HTML，但本质完全不同。最关键的一条：
//   HTML 是【静态标签】；JSX 是【JavaScript 表达式】。
//   JSX 会被编译成函数调用，所以它能写循环、判断、变量、函数调用、复用，
//   这些用纯 HTML 一样都做不到。
//
// 其余必须遵守的区别（写错就直接编译报错）：
//   HTML 的 class      → JSX 必须写 className（class 是 JS 保留字）
//   HTML 的 <!-- -->   → JSX 必须写成花括号包起来的块注释
//   HTML 的 onclick    → JSX 必须写成驼峰 onClick
//   HTML 的 <br>       → JSX 必须自闭合写成 <br />
//   HTML 的 tabindex   → JSX 必须写 tabIndex
//
// 结论：本文件最终【产出】的是标准 HTML，
//       但写它的【语言】是 TypeScript，浏览器实际收到的 HTML 是 JS 算出来的。
//
// 【这个文件在项目里的角色】
// Next.js 的约定文件：src/app/layout.tsx 是"根布局"，由框架按路径自动挂载，
// 不需要（也不应该）在别处 import 它。
// 它相当于"所有页面共用的外层函数"：
//   Render(layout) { html { body { 导航栏; Render(当前页面); 页脚 } } }
// 切换页面时本文件不会重新渲染，只有中间的 children 被替换，
// 所以导航栏不闪、星空不会重画。
// ----------------------------------------------------------------------------


// ----------------------------------------------------------------------------
// 下面 7 行都是"导入"（import），但分两类，性质完全不同。
// ----------------------------------------------------------------------------

// 【第 1 行】只导入一个"类型"，不导入任何可执行的代码。
// 关键字 import type 是关键：编译器只把它当类型信息用，
// 生成 JS 时这一行会被【整个删掉】，运行时不存在。
// 类似 C++ 头文件里的声明：编译完就没了，不占运行时任何空间。
import type { Metadata } from "next";

// 【第 2 行】导入全局样式表。这是"副作用导入"：
// 不接收任何返回值，只为了让 globals.css 里的代码被执行
// （定义主题颜色变量、注册全部 @keyframes 动画）。
// 全站只需在这里导入一次，样式会自动作用于所有页面。
import "./globals.css";

// 【第 3~7 行】导入 5 个自定义组件。
// @/ 是 tsconfig.json 里配置的路径别名，等价于 src/，
// 所以 "@/components/providers" 实际指向 src/components/providers.tsx。
// 用别名是为了避免写成 "../../../components/..." 这种又长又脆弱的相对路径。
//
// 花括号 { Providers } 是"具名导入"：从那个模块里取出名叫 Providers 的导出。
// 如果模块是默认导出，就不加花括号，写成 import Providers from "..."。
import { Providers } from "@/components/providers";
import { Navbar } from "@/components/layout/navbar";
import { Footer } from "@/components/layout/footer";
import { AlgoClickDecorator } from "@/components/algo-decoration/algo-click-decorator";
import { BackgroundLayer } from "@/components/background/background-layer";


// ----------------------------------------------------------------------------
// metadata：Next.js 认识的"特殊导出"。
// 它不是被谁调用的函数，而是框架在渲染时读取它，自动往 HTML 的 <head>
// 里插入 <title> 和 <meta name="description">。
// 影响两件事：浏览器标签页上的文字、搜索引擎抓到的页面简介。
// ----------------------------------------------------------------------------
// export const = 导出一个常量。
// 冒号后面的 Metadata 是类型注解：这个对象必须符合 Metadata 的形状，
// 字段名写错编译器立刻报错。
export const metadata: Metadata = {
  // title 写成对象，是为了配置"标题模板"
  title: {
    // default：页面自己没设标题时，用这一串
    default: "Study Tracker · 让学习看得见",
    // template：子页面设了标题时套用这个格式，里面的 %s 会被替换。
    // 例：algorithm/page.tsx 写了 title:"算法竞赛" →
    //     浏览器标签页显示 "算法竞赛 · Study Tracker"
    template: "%s · Study Tracker",
  },
  // description：页面简介，会渲染成 <meta name="description" content="...">。
  // 太长时换行写；行尾的逗号是 JS 对象允许的"尾随逗号"，不算语法错误。
  description:
    "Study Tracker —— 让学习看得见：算法竞赛刷题计划、Codeforces 数据统计、算法扭蛋机。",
};


// ----------------------------------------------------------------------------
// RootLayout —— 本文件唯一的默认导出组件，也是整个站点的渲染入口。
// ----------------------------------------------------------------------------
// 这一行逐段拆解：
//   export default   → 把后面的东西作为本文件的"默认导出"。
//                      Next.js 规定布局/页面文件必须默认导出，硬性要求。
//   function         → 定义一个函数。在 React 里，"返回界面的函数"就叫组件。
//   RootLayout       → 函数名。框架不认这个名字，随便起（Home、Index 都行）。
//   ({ children }    → 参数"解构"：框架传进来的是一个对象，
//                      花括号直接从对象里取出 children 字段当变量用，
//                      相当于 C++ 里取结构体的某个成员。
//   最后 }) {         → 冒号后是类型注解，规定参数对象必须长成下面这个形状。
export default function RootLayout({
  // children 就是"当前页面的内容"：访问 / 时它等于主页组件，
  // 访问 /schedule 时它等于日程页组件 —— 由路由框架负责塞进来。
  children,
}: {
  // React.ReactNode 的类型含义："任何能显示的东西"：
  // 字符串、数字、HTML 元素、子组件、数组、null 全都算。
  // 类似一个万能类型（可以理解成 std::variant）。
  children: React.ReactNode;
}) {
  // return 返回 JSX。注意后面跟圆括号 ( 而不是花括号 {，
  // 因为要返回的是一个"表达式"，圆括号只是为了能换行排版。
  return (
    // ------------------------------------------------------------------------
    // <html> —— 整个文档的最外层标签。
    // 根布局必须渲染 <html> 和 <body>，这是 Next.js 的硬性规定。
    //
    // 这一行有 3 个属性，逐个解释：
    //
    //   lang="zh-CN"
    //       声明页面语言是简体中文。影响：屏幕阅读器的发音、浏览器
    //       "是否提示翻译此页"的判断、搜索引擎的语言归类。
    //
    //   className="dark"
    //       给 <html> 加 dark 类名 = 默认开启深色主题。
    //       Tailwind 里所有 dark: 前缀样式，以及 globals.css 里
    //       `.dark { ... }` 定义的一整套颜色变量，全靠这个类名生效。
    //       （你的主题切换按钮做的唯一一件事，就是增删这个类名。）
    //
    //   suppressHydrationWarning
    //       抑制一条 React 警告。原因很具体：
    //       服务端先渲染出静态 HTML 发给浏览器；浏览器加载 JS 后要"接管"
    //       这份 HTML（叫水合 hydration），接管时会逐项比对两边是否一致。
    //       主题相关的类名可能在接管前就被改动 → 比对必然不一致 → React 报警。
    //       这个属性表示"该元素允许有差异，不要报"。
    // ------------------------------------------------------------------------
    <html lang="zh-CN" className="dark" suppressHydrationWarning>
      {/* ------------------------------------------------------------------
        <body> —— 文档的"身体"，页面上所有可见内容都装在它里面。

        这一行挂了 5 个 Tailwind 类名，一个类名就是一条预设 CSS 规则：

          min-h-screen    → min-height: 100vh，至少占满一屏高
                            （vh = 视口高度的 1%，100vh 就是整屏高）

          bg-background   → background-color 用主题变量 --background
                            （深色主题下就是接近黑的深空色）

          font-sans       → 使用无衬线字体栈
                            （本项目配成了系统字体，绕开国内加载 Google 字体失败）

          text-foreground → 文字颜色用主题变量 --foreground
                            （深色主题下是浅色字，保证对比度）

          antialiased     → 字体抗锯齿，文字边缘更细腻

        Tailwind 的思路就是用类名"拼"样式，不写单独的 .css 文件，
        省掉起名字和跨文件找样式的麻烦。
      ------------------------------------------------------------------ */}
      <body className="min-h-screen bg-background font-sans text-foreground antialiased">
        {/* ----------------------------------------------------------------
          <Providers> —— 把 5 个"数据管家"一次性套在最外层。

          这 5 个管家分别管：主题(theme)、设置(settings)、任务与扭蛋(study)、
          单词(english)、日程(schedule)，它们都是 React Context。

          Context 是什么：相当于"全局共享变量 + 自动通知"。
          套在最外层之后，任何深度的子组件都能直接调用 useSettings()、
          useEnglish() 之类的钩子读写数据，【不需要一层层往下传参数】。
          而且数据一变，用到它的组件会自动重画。
        ---------------------------------------------------------------- */}
        <Providers>
          {/* --------------------------------------------------------------
            <BackgroundLayer /> —— 全屏壁纸背景层（视频循环 + 深色遮罩）。

            三个要点：
              1. 末尾的 / 表示"自闭合"：这个组件没有子内容。
                 等价于 HTML 里 <img /> 那种写法。JSX 里所有没有子元素的
                 标签都必须这样自闭合，不能只写 <BackgroundLayer>。
              2. 它内部渲染一个全屏 <video> 播放壁纸，再叠 2 层深色遮罩，
                 保证白色文字在明亮区域也看得清。
              3. 壁纸文件在 public/wallpaper/，已被 .gitignore 排除、不会上传；
                 文件缺失或加载失败时，它会自动回退到 Canvas 星空背景。
          -------------------------------------------------------------- */}
          <BackgroundLayer />

          {/* --------------------------------------------------------------
            这一层 div 是"正经内容"的容器，类名各有职责：

              relative      → position: relative
                              建立层叠上下文，并作为内部绝对定位元素的参照物
              z-10          → 层级 = 10，高于星空背景，避免内容被星星盖住
              flex          → display: flex，开启弹性布局
              flex-col      → 主轴改纵向（默认横向），即"从上往下排"
              min-h-screen  → 至少一屏高

            为什么用 flex-col + 下面 main 上的 flex-1：
            内容很少的页面（比如主页）也能把页脚"压"到屏幕最底部，
            而不是尴尬地悬在页面中间。
          -------------------------------------------------------------- */}
          <div className="relative z-10 flex min-h-screen flex-col">
            {/* 顶部导航栏组件：4 个标签页 + 设置入口 + 亮暗主题切换按钮。
                没有子内容，所以自闭合。 */}
            <Navbar />

            {/* ------------------------------------------------------------
              <main> —— 语义标签，代表"本页的主体内容"
              （和 <nav>、<header>、<footer> 同类，主要给屏幕阅读器和
                搜索引擎看，对视觉效果没有直接影响）。

              这一行的类名逐个解释：
                mx-auto      → 左右 auto 外边距 = 水平居中
                w-full       → 宽度撑满父容器
                max-w-6xl    → 但最宽限制在 72rem（约 1152px），
                               否则在超大显示器上会被拉得太宽、文字难读
                flex-1       → 占满剩余高度，从而把页脚顶到最底部
                px-4         → 左右内边距 1rem
                py-6         → 上下内边距 1.5rem
                sm:px-6      → 响应式：屏幕 ≥640px 时左右内边距改成 1.5rem
                               （sm / md / lg 是 Tailwind 的断点前缀，
                                含义是"这个尺寸及以上"）

              这是全外壳最关键的位置：
                {children} 就是"当前页面内容"被插入的地方。
                访问 /         → 插入 LandingPage
                访问 /english  → 插入英语页
                访问 /schedule → 插入日程页
              一个外壳服务所有页面，这就是布局复用的意义。
            ------------------------------------------------------------ */}
            <main className="mx-auto w-full max-w-6xl flex-1 px-4 py-6 sm:px-6">
              {/* 花括号 = "把一个 JS 变量的值渲染到这里"。
                  这也不是 HTML 语法：HTML 里没办法直接插一个变量。 */}
              {children}
            </main>

            {/* 页脚组件：说明文字 + 「声明」链接（跳转 /about） */}
            <Footer />
          </div>

          {/* --------------------------------------------------------------
            <AlgoClickDecorator /> —— 点击空白处，随机飘出算法知识卡片的装饰。

            为什么放在这个位置（而不是上面那个 z-10 容器里）：
            它内部通过 Portal（传送门）把卡片直接渲染到 document.body 上，
            并设置 pointer-events: none，所以它只"监听"点击、不"拦截"点击，
            永远不会挡住你点按钮、链接或输入框。
          -------------------------------------------------------------- */}
          <AlgoClickDecorator />
        </Providers>
      </body>
    </html>
  );
  // 这个分号是 return 语句的结束符。
  // 到这里组件函数结束：它"返回"了一整棵界面树。
}
